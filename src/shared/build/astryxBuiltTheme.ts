import { parseSync, type Plugin } from 'vite';

const GENERATED = '@generated by `astryx theme build`';
const DIST = '/@astryxdesign/core/dist/';
const HOOK = `${DIST}theme/useTheme.js?hook`;
const RESOLVE = 'resolveThemeTokens(';
const LEFT_OUT =
  "`Astryx read the built theme's ${field}, which src/shared/build/astryxBuiltTheme.ts leaves out.`";

/**
 * What a built theme carries that Astryx reads only to generate its CSS, which `astryx theme
 * build` has already written to the theme's stylesheet. `tokens` stays as an empty object, since
 * `useTheme` resolves them, and the toasts that call it read only its mode.
 */
const GENERATOR_FIELDS = [
  'tokens',
  'components',
  '__onDark',
  '__onLight',
  '__localTokenOwners',
  '__localTokenLineage',
];

/**
 * The Astryx modules the build ships that read the theme object, and what each reads. All of it
 * stays in a built theme, apart from the tokens `useTheme` resolves, which none of them use.
 */
const THEME_READERS: Record<string, string> = {
  'Icon/globalIconRegistry.js': 'icons',
  'Indicator/indicatorRegistry.js': 'indicators',
  'Toast/Toast.js': "useTheme's mode",
  'hooks/useAutoMediaMode.js': "useTheme's tokens, only as a sign the theme changed",
  'theme/themeRegistry.js': 'the theme, by name',
  'theme/useTheme.js': 'name, and the theme for the hooks it serves',
  'utils/touchPresentation.js': '__adaptations.widthBreakpoints',
};

const READS_THEME =
  /\b(?:useTheme|useThemeDefinition|getRegisteredThemes?)\(|\b(?:use|useContext)\(ThemeContext\)/;
const COMMENT = /\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm;

/**
 * Leaves a built theme's generator fields off the first load, where they cost about 3 KB gzip.
 * The theme's stylesheet already holds what they make, and Astryx reads the rest of the object.
 *
 * With `isTrapped`, each field the build leaves out becomes a getter that throws, and `useTheme`'s
 * resolved tokens throw when read, so a suite driving that build fails wherever Astryx reads what
 * is gone. The build fails if a module it ships that reads the theme isn't in `THEME_READERS`.
 */
export function astryxBuiltTheme({ isTrapped = false } = {}): Plugin {
  // The Astryx modules that read the theme, by id, each with its path within `dist`.
  const readers = new Map<string, string>();
  return {
    name: 'astryx-built-theme',
    apply: 'build',
    enforce: 'pre',
    applyToEnvironment: (environment) => environment.name === 'client',
    buildStart() {
      readers.clear();
    },
    transform(code, id) {
      try {
        if (isAppTheme(id, code)) return { code: leanBuiltTheme(code, isTrapped), map: null };
        if (isTrapped && id.endsWith(HOOK)) return { code: trapResolvedTokens(code), map: null };
      } catch (error) {
        return this.error(String(error));
      }
      const reader = readerOf(id);
      if (reader !== null && READS_THEME.test(code.replace(COMMENT, ''))) readers.set(id, reader);
      return null;
    },
    generateBundle(_, bundle) {
      const unlisted = new Set<string>();
      for (const output of Object.values(bundle)) {
        if (output.type !== 'chunk') continue;
        for (const [id, rendered] of Object.entries(output.modules)) {
          const reader = readers.get(id);
          if (reader && rendered.renderedLength > 0 && !(reader in THEME_READERS)) {
            unlisted.add(reader);
          }
        }
      }
      if (!unlisted.size) return;
      this.error(
        `${[...unlisted].join(', ')} read the theme, whose generator fields the build leaves out. ` +
          'Check what each reads, build with THEME_TRAPS=1 and run the e2e suite, then list it ' +
          'in THEME_READERS.',
      );
    },
  };
}

/**
 * A built theme's module with its generator fields left out, or, with `isTrapped`, each made a
 * getter that throws. Throws if the module no longer exports one theme with every such field.
 */
export function leanBuiltTheme(code: string, isTrapped: boolean): string {
  const { program } = parseSync('theme.js', code);
  const themes = program.body.flatMap((node) =>
    node.type === 'ExportNamedDeclaration' && node.declaration?.type === 'VariableDeclaration'
      ? node.declaration.declarations.flatMap(({ init }) =>
          init?.type === 'ObjectExpression' ? [init] : [],
        )
      : [],
  );
  const [theme] = themes;
  if (themes.length !== 1 || !theme) {
    throw new Error('A built theme no longer exports exactly one theme object.');
  }
  const fields = theme.properties.map((property) => {
    if (property.type !== 'Property' || property.key.type !== 'Identifier') {
      throw new Error('A built theme has a field the build cannot name.');
    }
    const source = code.slice(property.start, property.end);
    if (!source.startsWith(property.key.name)) {
      throw new Error('The parser placed a built theme field where its code is not.');
    }
    return { name: property.key.name, source };
  });
  const missing = GENERATOR_FIELDS.filter((name) => !fields.some((field) => field.name === name));
  if (missing.length) throw new Error(`A built theme no longer has ${missing.join(', ')}.`);

  const kept = fields.flatMap(({ name, source }) => {
    if (!GENERATOR_FIELDS.includes(name)) return [source];
    if (isTrapped) return [`get ${name}() { return leftOut(${JSON.stringify(name)}); }`];
    return name === 'tokens' ? ['tokens: {}'] : [];
  });
  const lean = `{\n  ${kept.join(',\n  ')},\n}`;
  return (
    code.slice(0, theme.start) +
    lean +
    code.slice(theme.end) +
    (isTrapped ? `\nfunction leftOut(field) {\n  throw new Error(${LEFT_OUT});\n}\n` : '')
  );
}

/**
 * `useTheme`'s own module with the tokens it resolves made an object that throws when read, as
 * they would resolve to Astryx's defaults without the built theme's. Throws if the hook no longer
 * resolves them in one place.
 */
export function trapResolvedTokens(code: string): string {
  const at = code.indexOf(RESOLVE);
  if (at < 0 || code.includes(RESOLVE, at + 1)) {
    throw new Error(`Astryx's useTheme no longer calls ${RESOLVE}) once.`);
  }
  return (
    code.slice(0, at) +
    'unresolvedTokens(' +
    code.slice(at + RESOLVE.length) +
    `\nfunction unresolvedTokens() {\n  return new Proxy({}, {\n    get(_, name) {\n` +
    `      if (typeof name === 'symbol') return undefined;\n` +
    `      throw new Error(\`Astryx read the theme's \${name} through useTheme, which the build ` +
    'resolves from no tokens.`);\n    },\n  });\n}\n'
  );
}

/** Whether a module is a theme the app built itself, rather than one a package ships. */
function isAppTheme(id: string, code: string): boolean {
  return /\.m?js$/.test(id) && !id.includes('/node_modules/') && code.includes(GENERATED);
}

/** An Astryx module's path within its `dist`, or null for any other module. */
function readerOf(id: string): string | null {
  const at = id.indexOf(DIST);
  return at < 0 ? null : id.slice(at + DIST.length).replace(/\?.*$/, '');
}
